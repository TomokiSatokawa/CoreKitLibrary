using System.Collections.Generic;
using System.IO;
using System.Text;
using UnityEditor;
using UnityEngine;

namespace CoreKit.DynamicEnum.Editor
{
    /// <summary>
    /// DynamicEnumDefinitionÇÃInspectorÇä«óùÇ∑ÇÈ
    /// </summary>
    [CustomEditor(typeof(DynamicEnumDefinition))]
    public class DynamicEnumDefinitionEditor : UnityEditor.Editor
    {
        private const string OutputDirectory = "Assets/Generated/DynamicEnums";
        private const string Namespace = "Generated.DynamicEnums";

        private SerializedProperty _className;
        private SerializedProperty _entries;

        private void OnEnable()
        {
            _className = serializedObject.FindProperty("_className");
            _entries = serializedObject.FindProperty("_entries");
        }

        public override void OnInspectorGUI()
        {
            serializedObject.Update();

            EditorGUILayout.PropertyField(_className);

            EditorGUILayout.Space(4);

            for (int i = 0; i < _entries.arraySize; i++)
            {
                var entry = _entries.GetArrayElementAtIndex(i);
                var name = entry.FindPropertyRelative("Name");

                EditorGUILayout.BeginHorizontal();

                name.stringValue = EditorGUILayout.TextField(
                    name.stringValue);

                if (GUILayout.Button("-", GUILayout.Width(24)))
                {
                    _entries.DeleteArrayElementAtIndex(i);
                    break;
                }

                EditorGUILayout.EndHorizontal();
            }

            EditorGUILayout.Space(4);

            if (GUILayout.Button("+ Add Element"))
            {
                int index = _entries.arraySize;
                _entries.InsertArrayElementAtIndex(index);

                var entry = _entries.GetArrayElementAtIndex(index);

                entry.FindPropertyRelative("Name").stringValue = "New Element";
                entry.FindPropertyRelative("Guid").stringValue =
                    System.Guid.NewGuid().ToString("N");
            }

            EditorGUILayout.Space(8);

            if (GUILayout.Button("Generate Code"))
            {
                serializedObject.ApplyModifiedProperties();
                GenerateCode((DynamicEnumDefinition)target);
                return;
            }

            serializedObject.ApplyModifiedProperties();
        }

        //AI
        private static void GenerateCode(DynamicEnumDefinition definition)
        {
            Directory.CreateDirectory(OutputDirectory);

            string className = SanitizeIdentifier(definition.ClassName);
            string previousClassName = definition.PreviousClassName;

            // ãåÉtÉ@ÉCÉãÇçÌèú
            if (!string.IsNullOrEmpty(previousClassName) &&
                previousClassName != className)
            {
                string oldPath = Path.Combine(
                    OutputDirectory, previousClassName + ".g.cs");

                if (File.Exists(oldPath))
                    File.Delete(oldPath);

                if (File.Exists(oldPath + ".meta"))
                    File.Delete(oldPath + ".meta");
            }

            var builder = new StringBuilder();

            builder.AppendLine("// <auto-generated />");
            builder.AppendLine();
            builder.AppendLine($"namespace {Namespace}");
            builder.AppendLine("{");
            builder.AppendLine($"    public static class {className}");
            builder.AppendLine("    {");

            var usedNames = new HashSet<string>();

            foreach (var entry in definition.Entries)
            {
                string fieldName = SanitizeIdentifier(entry.Name);

                if (!usedNames.Add(fieldName))
                    continue;

                builder.AppendLine(
                    $"        public static readonly CoreKit.DynamicEnum.DynamicEnumValue {fieldName} =");
                builder.AppendLine(
                    $"            new CoreKit.DynamicEnum.DynamicEnumValue(\"{entry.Guid}\");");
                builder.AppendLine();
            }

            builder.AppendLine("    }");
            builder.AppendLine("}");

            string path = Path.Combine(
                OutputDirectory, className + ".g.cs");

            File.WriteAllText(path, builder.ToString(), Encoding.UTF8);

            definition.SetPreviousClassName(className);

            EditorUtility.SetDirty(definition);
            AssetDatabase.SaveAssets();
            AssetDatabase.Refresh();
        }
        private static string SanitizeIdentifier(string value)
        {
            if (string.IsNullOrWhiteSpace(value))
                return "Unnamed";

            var builder = new StringBuilder();

            foreach (char c in value)
            {
                builder.Append(
                    char.IsLetterOrDigit(c) || c == '_' ? c : '_');
            }

            if (builder.Length == 0 ||
                (!char.IsLetter(builder[0]) && builder[0] != '_'))
            {
                builder.Insert(0, '_');
            }

            string result = builder.ToString();

            if (Keywords.Contains(result))
                result += "_";

            return result;
        }

        private static readonly HashSet<string> Keywords = new()
        {
            "class", "struct", "enum", "namespace", "public",
            "private", "static", "readonly", "new", "return",
            "if", "else", "switch", "case", "default", "void",
            "int", "float", "string", "bool", "object", "base",
            "this", "null", "true", "false", "for", "foreach",
            "while", "do", "break", "continue", "using", "const",
            "event", "delegate", "interface", "operator", "ref",
            "out", "in", "params", "is", "as", "typeof", "sizeof",
            "try", "catch", "finally", "throw", "checked",
            "unchecked", "lock", "unsafe", "fixed", "volatile",
            "override", "virtual", "abstract", "sealed", "extern",
            "internal", "protected", "explicit", "implicit",
            "get", "set", "value", "where", "yield", "async",
            "await", "var", "dynamic", "nameof"
        };
    }
}