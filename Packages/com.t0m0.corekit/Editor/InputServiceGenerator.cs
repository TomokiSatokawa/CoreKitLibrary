using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;
using UnityEngine;
using UnityEngine.InputSystem;

namespace CoreKit.Inputs.Editor
{
    public class InputServiceGenerator : AssetPostprocessor
    {
        private const string OutputPath = "Assets/Generated/InputService.cs";

        private static void OnPostprocessAllAssets(string[] imported, string[] d, string[] m, string[] f)
        {
            var target = InputSystem.actions;
            if (target == null) return;
            if (imported.Contains(AssetDatabase.GetAssetPath(target))) Generate(target);
        }

        [MenuItem("CoreKit/Input/Generate InputService")]
        private static void GenerateMenu()
        {
            if (InputSystem.actions == null)
            {
                Debug.LogError("Project-wide Actionsが未設定です");
                return;
            }
            Generate(InputSystem.actions);
        }

        private static void Generate(InputActionAsset asset)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated> CoreKit.Inputs により自動生成。手編集しないでください </auto-generated>");
            sb.AppendLine("using CoreKit.Inputs;");
            sb.AppendLine();
            sb.AppendLine("public static class InputService");
            sb.AppendLine("{");

            foreach (var map in asset.actionMaps)
            {
                sb.AppendLine($"    public static class {Id(map.name)}");
                sb.AppendLine("    {");
                foreach (var a in map.actions)
                {
                    string type;
                    if (a.expectedControlType == "Vector2") type = "InputVector2";
                    else if (a.type == InputActionType.Button || a.expectedControlType == "Button") type = "InputButton";
                    else
                    {
                        Debug.LogWarning($"[CoreKit.Inputs] '{map.name}/{a.name}'（{a.expectedControlType}）は未対応のため生成をスキップしました");
                        continue;
                    }
                    sb.AppendLine($"        public static readonly {type} {Id(a.name)} = new {type}(\"{map.name}/{a.name}\");");
                }
                sb.AppendLine("    }");
            }
            sb.AppendLine("}");

            var text = sb.ToString();
            if (File.Exists(OutputPath) && File.ReadAllText(OutputPath) == text) return; // 変更なしなら再コンパイルを避ける

            Directory.CreateDirectory(Path.GetDirectoryName(OutputPath));
            File.WriteAllText(OutputPath, text);
            AssetDatabase.ImportAsset(OutputPath);
        }

        // C#の識別子として使える形に変換
        private static string Id(string name)
        {
            var s = new string(name.Select(c => char.IsLetterOrDigit(c) ? c : '_').ToArray());
            return char.IsDigit(s[0]) ? "_" + s : s;
        }
    }
}