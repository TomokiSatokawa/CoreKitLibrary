#if UNITY_EDITOR
using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;

/// <summary>CoreKitタブから、Build Settingsのシーン移動メニューを生成する</summary>
public static class SceneMenuGenerator
{
    // 生成先（Packagesは書き込み不可なのでAssets配下）
    private const string OutputPath = "Assets/Generated/Editor/SceneTabWindow.cs";

    [MenuItem("CoreKit/Generate/Scene Menu")]
    public static void Generate()
    {
        // 有効なシーンのみ。GetScenePathByBuildIndexのindexは「有効なシーンだけの連番」なのでここで合わせる
        var scenes = EditorBuildSettings.scenes
            .Where(s => s.enabled)
            .ToArray();

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated> CoreKit > Generate > Scene Menu で生成されました。手動編集は再生成で消えます。");
        sb.AppendLine("#if UNITY_EDITOR");
        sb.AppendLine("using UnityEditor;");
        sb.AppendLine("using UnityEditor.SceneManagement;");
        sb.AppendLine("using UnityEngine.SceneManagement;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>Menu画面にシーンを移動するボタンを追加</summary>");
        sb.AppendLine("public static class SceneTabWindow");
        sb.AppendLine("{");

        for (int i = 0; i < scenes.Length; i++)
        {
            string sceneName = Path.GetFileNameWithoutExtension(scenes[i].path);
            string label = SanitizeMenuLabel(sceneName);

            // priorityを指定して、10以上でも並びが 0,1,2,...,10 になるようにする
            sb.AppendLine($"    [MenuItem(\"Scene/{i} {label}\", false, {100 + i})]");
            sb.AppendLine($"    public static void Scene{i:00}()");
            sb.AppendLine("    {");
            sb.AppendLine("        EditorSceneManager.SaveOpenScenes();");
            sb.AppendLine($"        OpenScene({i});");
            sb.AppendLine("    }");
            sb.AppendLine();
        }

        sb.AppendLine("    private static void OpenScene(int sceneIndex)");
        sb.AppendLine("    {");
        sb.AppendLine("        string scenePath = SceneUtility.GetScenePathByBuildIndex(sceneIndex);");
        sb.AppendLine("        if (!string.IsNullOrEmpty(scenePath))");
        sb.AppendLine("        {");
        sb.AppendLine("            EditorSceneManager.OpenScene(scenePath);");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine("#endif");

        string dir = Path.GetDirectoryName(OutputPath);
        if (!Directory.Exists(dir)) Directory.CreateDirectory(dir);

        File.WriteAllText(OutputPath, sb.ToString(), new UTF8Encoding(false));
        AssetDatabase.ImportAsset(OutputPath);

        UnityEngine.Debug.Log($"[CoreKit] SceneTabWindow を生成しました（{scenes.Length} シーン）: {OutputPath}");
    }

    // MenuItemで特殊な意味を持つ文字（% # & _）と、文字列を壊す文字を除去
    private static string SanitizeMenuLabel(string name)
    {
        return name
            .Replace("\\", "")
            .Replace("\"", "")
            .Replace("%", "")
            .Replace("#", "")
            .Replace("&", "")
            .Replace("_", " ");
    }
}
#endif